const { chromium } = require('playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const base = process.env.BRUNCH_TEST_URL || 'http://127.0.0.1:3100'
const inbox = process.env.BRUNCH_MAILPIT_URL || 'http://127.0.0.1:18026'
for (const address of [base, inbox]) assert(['127.0.0.1', 'localhost'].includes(new URL(address).hostname), 'Browser tests only run against localhost')
const out = 'output/browser'
fs.mkdirSync(out, { recursive: true })
const run = Date.now()
const guest = `guest-${run}@example.test`
const customer = `customer-${run}@example.test`
async function mailFor(address, subject) {
  for (let i = 0; i < 60; i++) {
    const data = await fetch(`${inbox}/api/v1/messages?limit=100`).then(r => r.json())
    const message = data.messages.find(m => m.To.some(to => to.Address === address) && (!subject || m.Subject.includes(subject)))
    if (message) return fetch(`${inbox}/api/v1/message/${message.ID}`).then(r => r.json())
    await new Promise(r => setTimeout(r, 500))
  }
  throw new Error(`No captured message for ${address}`)
}
async function checkout(page, address, payment) {
  await page.locator('.product-card').first().getByRole('button', { name: /Přidat .* do košíku/ }).click()
  await page.locator('.header-cart').click()
  await page.getByRole('button', { name: 'Pokračovat k doručení', exact: true }).click()
  await page.locator('[name=email]').fill(address)
  await page.locator('[name=street-address]').fill('Testovací 12')
  await page.locator('[name=city]').fill('Praha')
  await page.locator('[name=postal-code]').fill('110 00')
  await page.locator('[name=notes]').fill('3. patro, zvonek Test, předat na recepci.')
  await page.getByRole('button', { name: 'Zkontrolovat objednávku', exact: true }).click()
  await page.locator(`[name=payment-method][value=${payment}]`).check()
  await page.screenshot({ path: `${out}/${payment}-checkout.png`, fullPage: false })
  const response = page.waitForResponse(r => r.url() === `${base}/api/orders` && r.request().method() === 'POST')
  await page.getByRole('button', { name: /Objednat s povinností platby/ }).click()
  const result = await response
  assert.equal(result.status(), 200, await result.text())
  const order = await result.json()
  assert.equal(order.email, address)
  assert.equal(order.payment_method, payment)
  assert.equal(order.total_cents, 16800)
  assert.equal(order.notes, '3. patro, zvonek Test, předat na recepci.')
  await page.getByRole('heading', { name: 'Objednávku jsme přijali.' }).waitFor()
  assert.equal(await page.locator('.header-cart .cart-count').innerText(), '0')
  const captured = await mailFor(address, order.number)
  assert(captured.Text.includes(order.number))
  assert(captured.Text.includes('3. patro'))
  await page.getByRole('button', { name: 'Zpátky na svačiny', exact: true }).click()
  return order
}
;(async () => {
  const browser = await chromium.launch({ headless: true })
  const errors = []
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
    const page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    await page.goto(base)
    await page.locator('.product-card').first().waitFor()
    await page.screenshot({ path: `${out}/storefront-desktop.png`, fullPage: true })
    const guestOrder = await checkout(page, guest, 'cash_on_delivery')
    await page.locator('.account-button').click()
    await page.locator('[name=login-email]').fill(customer)
    await page.getByRole('button', { name: 'Poslat přihlašovací odkaz', exact: true }).click()
    const login = await mailFor(customer, 'Přihlášení')
    const link = login.Text.match(/https?:\/\/[^\s]+login_token=[a-f0-9]+/)[0]
    await page.goto(link)
    await page.getByRole('button', { name: 'Potvrdit přihlášení', exact: true }).waitFor()
    assert(!page.url().includes('login_token'), 'Token stripped from browser URL')
    await page.getByRole('button', { name: 'Potvrdit přihlášení', exact: true }).click()
    await page.getByRole('heading', { name: 'Můj účet', exact: true }).waitFor()
    assert(!(await page.locator('.account-orders').innerText()).includes(guestOrder.number))
    await page.getByRole('button', { name: 'Zavřít účet' }).click()
    const memberOrder = await checkout(page, customer, 'card_on_delivery')
    await page.locator('.account-button').click()
    await page.locator(".account-orders").getByText(memberOrder.number, { exact: true }).waitFor()
    await page.locator(".account-order summary").first().click()
    await page.screenshot({ path: `${out}/customer-orders.png`, fullPage: false })
    await page.getByRole('button', { name: 'Přidat znovu do košíku', exact: true }).click()
    await page.getByRole('heading', { name: 'Váš košík', exact: true }).waitFor()
    assert.equal(await page.locator('.header-cart .cart-count').innerText(), '1')
    await page.getByRole('button', { name: 'Zavřít košík' }).click()
    await page.reload()
    await page.locator('.product-card').first().waitFor()
    assert.equal(await page.locator('.header-cart .cart-count').innerText(), '1', 'cart survives reload')
    await page.locator('.account-button').click()
    await page.getByRole('button', { name: 'Odhlásit', exact: true }).click()
    await page.getByRole('heading', { name: 'Účet bez hesla', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Zavřít účet' }).click()
    const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, deviceScaleFactor: 1 })
    const phone = await mobile.newPage()
    phone.on('pageerror', e => errors.push(e.message))
    await phone.goto(base)
    await phone.locator('.product-card').first().waitFor()
    assert(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'No horizontal overflow on mobile')
    await phone.screenshot({ path: `${out}/storefront-mobile.png`, fullPage: true })
    await phone.locator('.product-card').first().getByRole('button', { name: /Přidat .* do košíku/ }).click()
    await phone.locator('.mobile-cart button').click()
    await phone.getByRole('button', { name: 'Pokračovat k doručení', exact: true }).click()
    await phone.screenshot({ path: `${out}/checkout-mobile.png`, fullPage: false })
    assert(await phone.locator('.cart-dialog').evaluate(d => d.getBoundingClientRect().width <= window.innerWidth), 'Mobile dialog fits viewport')
    assert.deepEqual(errors, [], 'No browser JavaScript errors')
    console.log(JSON.stringify({ passed: ['guest cash checkout', 'customer confirmation email', 'email registration and login', 'guest isolation', 'member card checkout', 'order history', 'repeat order', 'persistent cart', 'logout', 'mobile viewport'], guestOrder: guestOrder.number, memberOrder: memberOrder.number, screenshots: out }, null, 2))
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exit(1) })
