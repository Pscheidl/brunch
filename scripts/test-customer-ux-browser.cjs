    assert.equal(await reorder.evaluate(() => JSON.parse(localStorage.getItem('brunch-variants') || '{}')['4']), 'Šunka a sýr')
    checks.push('Reorder never overwrites another variant already in the basket')

    const packs = await newPage()
    await packs.goto(base)
