    await packSection.getByRole('combobox', { name: 'Počet lidí', exact: true }).selectOption('10')
    await packSection.getByRole('button', { name: 'Přidat výběr do košíku', exact: true }).click()
    assert.equal(await packs.locator('.header-cart .cart-count').innerText(), '0', 'A pack cannot silently shrink to available stock')
    await closeCart(packs)
    await packSection.getByRole('combobox', { name: 'Počet lidí', exact: true }).selectOption('5')
    await packSection.getByRole('button', { name: 'Přidat výběr do košíku', exact: true }).click()
    assert.equal(await quantity(packs.locator('.cart-dialog'), 'Koláčky').inputValue(), '5')
    await closeCart(packs)
    await packSection.getByRole('button', { name: 'Přidat výběr do košíku', exact: true }).click()
    assert.equal(await quantity(packs.locator('.cart-dialog'), 'Koláčky').inputValue(), '5', 'Adding another pack cannot silently produce a partial pack')
    checks.push('Team packs respect variants and available stock without silently changing requested pack sizes')

    const teamImport = { team_id: '4b392dcb-0784-4720-bd1e-a83d57fe10b5', revision: 1, items: [{ product_id: 1, quantity: 3 }], notes: 'Tým: Jana 2 ks, Petr 1 ks' }
