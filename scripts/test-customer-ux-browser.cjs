    if (await page.getByRole('button', { name: 'Pokračovat k doručení', exact: true }).isVisible()) await page.getByRole('button', { name: 'Pokračovat k doručení', exact: true }).click()
    assert.equal(await page.locator('.checkout-form [name=name]').inputValue(), 'Jana Testovací')
    assert.equal(await page.locator('.checkout-form [name=notes]').inputValue(), 'Předat na recepci')
    assert.equal(await page.locator('.checkout-form [name=billing-name]').inputValue(), 'Testovací firma')
