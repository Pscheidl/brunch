    await stale.locator('.header-cart').click()
    assert.equal(await stale.locator('.cart-dialog .variant-selector').count(), 0)
    await stale.getByRole('button', { name: 'Odebrat celou položku: Sendvičový box', exact: true }).click()
    await closeCart(stale)
    await card(stale, 'Sendvičový box').getByRole('button', { name: 'Přidat Sendvičový box do košíku', exact: true }).click()
    assert.equal(await stale.locator('.header-cart .cart-count').innerText(), '1')
    checks.push('Removed variants are cleared and product can be added again')

    const previousOrder = { id: 'previous-1', number: 'OLD-1', status: 'delivered', payment_method: 'card_on_delivery', payment_status: 'paid', subtotal_cents: 43000, delivery_fee_cents: 0, total_cents: 43000, email: 'jana@example.test', name: 'Jana Testovací', phone: '+420 777 123 456', street: 'Testovací 1', city: 'Praha', postal_code: '11000', delivery_date: '2026-11-20', delivery_slot: '07:00–09:00', items: [{ product_id: 4, name: 'Sendvičový box (Zeleninový)', quantity: 1, unit_price_cents: 43000, total_cents: 43000, variant: 'Zeleninový' }] }
    const reorder = await newPage({ local: { 'brunch-cart-v2': { 4: 2 }, 'brunch-variants': { 4: 'Šunka a sýr' } } }, products, [previousOrder])
    await reorder.goto(base)
    await reorder.getByRole('button', { name: 'Můj účet', exact: true }).waitFor()
    await reorder.getByRole('button', { name: 'Můj účet', exact: true }).click()
    await reorder.getByRole('button', { name: 'Přidat znovu do košíku', exact: true }).click()
