    assert.equal(await page.evaluate(() => sessionStorage.getItem('brunch-checkout-draft')), null)
    await page.getByRole('button', { name: 'Zpátky na svačiny', exact: true }).click()
    const completedDraft = await page.evaluate(() => JSON.parse(sessionStorage.getItem('brunch-checkout-draft') || 'null'))
    assert.ok(!completedDraft || !completedDraft.name, 'Completed customer details must not be restored into a new draft')
    checks.push('Product deep links/back, required variants, checkout draft reload, billing and variant snapshot, success draft cleanup')

    const changedCatalog = products.map(product => ({ ...product, variants: [...product.variants] }))
    const stale = await newPage({ local: { 'brunch-cart-v2': { 4: 1 }, 'brunch-variants': { 4: 'Šunka a sýr' } } }, changedCatalog)
